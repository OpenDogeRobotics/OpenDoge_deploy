#!/usr/bin/env bash
# ⚠️ 当前硬件为赤乌（CHIWU）原生 SocketCAN can0-can3；本脚本仅作
# gs_usb/达妙备选参考。当前接入见 docs/usb2can/chiwu_usb2can.md；
# 旧 DingLab 方案见 docs/legacy/README.md。
#
# 为达妙 USB2CANFD Dual（gs_usb）生成稳定的 can0-can3 命名规则。
#
# 两个双路模块的 4 个通道对应 4 个 USB interface 路径，例如：
#   1-1.2:1.0  -> 模块 A CAN1
#   1-1.2:1.1  -> 模块 A CAN2
#   1-1.3:1.0  -> 模块 B CAN1
#   1-1.3:1.1  -> 模块 B CAN2
# udev 规则按 USB interface 路径命名，而不是按枚举顺序，避免 can0-can3 互换。
#
# 用法:
#   # 先确认当前映射是正确的（用 verify_can_mapping.py），再冻结当前路径
#   sudo bash scripts/setup_can_names.sh --freeze-current
#
#   # 或显式指定接口路径
#   sudo bash scripts/setup_can_names.sh \
#       can0=1-1.2:1.0 can1=1-1.2:1.1 \
#       can2=1-1.3:1.0 can3=1-1.3:1.1
#
# 生成文件: /etc/udev/rules.d/70-opendoge-can.rules
# 执行后会 reload udev 并 trigger；若名称未立即变化，重新插拔两个模块。

set -euo pipefail

RULE_FILE="/etc/udev/rules.d/70-opendoge-can.rules"
FREEZE=0
declare -A MAP=()

usage() {
    awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --freeze-current) FREEZE=1 ;;
        can[0-3]=*) MAP["${1%%=*}"]="${1#*=}" ;;
        -h|--help) usage; exit 0 ;;
        *) echo "未知参数: $1" >&2; usage; exit 1 ;;
    esac
    shift
done

if [[ ${FREEZE} -eq 1 ]]; then
    for i in 0 1 2 3; do
        iface="can${i}"
        if [[ ! -e "/sys/class/net/${iface}" ]]; then
            echo "❌ ${iface} 不存在，无法冻结当前映射" >&2
            exit 1
        fi
        path="$(basename "$(readlink -f "/sys/class/net/${iface}/device" 2>/dev/null)" 2>/dev/null || true)"
        if [[ -z "${path}" ]]; then
            echo "❌ ${iface} 没有 USB device 路径（不是 gs_usb 设备？）" >&2
            exit 1
        fi
        MAP["${iface}"]="${path}"
    done
fi

if [[ ${#MAP[@]} -eq 0 ]]; then
    echo "❌ 没有提供映射。使用 --freeze-current 或 can0=... 参数。" >&2
    usage
    exit 1
fi

for i in 0 1 2 3; do
    iface="can${i}"
    if [[ -z "${MAP[${iface}]:-}" ]]; then
        echo "❌ 缺少 ${iface} 的映射" >&2
        exit 1
    fi
done

# 路径必须唯一，否则两个接口会抢同一个名字
unique_paths="$(printf '%s\n' "${MAP[can0]}" "${MAP[can1]}" "${MAP[can2]}" "${MAP[can3]}" | sort -u | wc -l)"
if [[ "${unique_paths}" -ne 4 ]]; then
    echo "❌ 四个接口的 USB 路径不唯一，检查映射：" >&2
    for i in 0 1 2 3; do echo "  can${i}=${MAP[can${i}]}" >&2; done
    exit 1
fi

if [[ ${EUID} -ne 0 ]]; then
    echo "❌ 需要 root: sudo bash $0 $*" >&2
    exit 1
fi

echo "生成的映射："
for i in 0 1 2 3; do
    echo "  can${i} <- ${MAP[can${i}]}"
done

if [[ -f "${RULE_FILE}" ]]; then
    backup="${RULE_FILE}.bak.$(date +%s)"
    cp -v "${RULE_FILE}" "${backup}"
fi

{
    echo "# Generated by scripts/setup_can_names.sh"
    echo "# DAMIAO USB2CANFD Dual / gs_usb stable naming"
    echo "# Do not edit by hand unless you know the USB interface paths."
    for i in 0 1 2 3; do
        echo "ACTION==\"add\", SUBSYSTEM==\"net\", KERNELS==\"${MAP[can${i}]}\", NAME=\"can${i}\""
    done
} > "${RULE_FILE}"

echo
echo "写入 ${RULE_FILE}"
cat "${RULE_FILE}"

udevadm control --reload-rules
udevadm trigger --action=add --subsystem-match=net
udevadm settle

echo
echo "已 reload udev。若 can0-can3 名称没有立即变化，请重新插拔两个模块或重启。"
echo "然后执行只读校验："
echo "  sudo python3 scripts/verify_can_mapping.py"
echo
echo "注意：如果板载原生 CAN 也占用 can0，本规则无法覆盖，需先禁用/改名原生接口。"
